use crate::model::Session;
use ewebsock::{Options, WsReceiver, WsSender};
use serde_json::{json, Value};
use std::sync::mpsc::{self, Receiver};
use std::thread;
use std::io::Read;
use std::time::Duration;

pub fn request_room(base_url: String, nickname: String, avatar: u8, code: Option<String>) -> Receiver<Result<Session, String>> {
    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        let base = base_url.trim().trim_end_matches('/');
        if !(base.starts_with("http://") || base.starts_with("https://")) {
            let _ = tx.send(Err("URL сервера должен начинаться с http:// или https://".into()));
            return;
        }
        let url = match code {
            Some(code) => format!("{base}/api/rooms/{code}/join"),
            None => format!("{base}/api/rooms"),
        };
        let agent = ureq::AgentBuilder::new()
            .timeout(Duration::from_secs(12))
            .build();
        let response = agent.post(&url).send_json(json!({ "name": nickname, "avatar": avatar }));
        let result: Result<Session, String> = match response {
            Ok(resp) => resp.into_json::<Session>().map_err(|err| err.to_string()),
            Err(ureq::Error::Status(code, resp)) => {
                let error = resp.into_json::<Value>().ok()
                    .and_then(|v| v.get("error")?.as_str().map(str::to_owned))
                    .unwrap_or_else(|| format!("Сервер ответил кодом {code}"));
                Err(error)
            }
            Err(err) => Err(format!("Не удалось связаться с сервером: {err}")),
        };
        let _ = tx.send(result);
    });
    rx
}

pub fn connect(base_url: &str, session: &Session) -> Result<(WsSender, WsReceiver), String> {
    let base = base_url.trim().trim_end_matches('/');
    let url = if let Some(rest) = base.strip_prefix("https://") {
        format!("wss://{rest}")
    } else if let Some(rest) = base.strip_prefix("http://") {
        format!("ws://{rest}")
    } else {
        return Err("Некорректный адрес сервера".into());
    };
    // The token is opaque and generated by the server. Never print or log this URL.
    let url = format!("{url}/api/rooms/{}/ws?token={}", session.code, session.token);
    ewebsock::connect(&url, Options::default()).map_err(|err| format!("WebSocket: {err}"))
}


// ZIPs are automatically shared by the host through the same Cloudflare room.
// Authentication uses a bearer header; room tokens are never included in logs.
pub fn upload_bundle(base_url: String, session: Session, bytes: Vec<u8>) -> Receiver<Result<String, String>> {
    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        let url = format!("{}/api/rooms/{}/bundle", base_url.trim().trim_end_matches('/'), session.code);
        let response = ureq::AgentBuilder::new().timeout(Duration::from_secs(25)).build()
            .post(&url)
            .set("authorization", &format!("Bearer {}", session.token))
            .set("content-type", "application/zip")
            .send_bytes(&bytes);
        let result = match response {
            Ok(r) => r.into_json::<Value>()
                .map(|v| v.get("packName").and_then(Value::as_str).unwrap_or("ZIP").to_owned())
                .map_err(|e| e.to_string()),
            Err(ureq::Error::Status(code, r)) => {
                let reason = r.into_json::<Value>().ok()
                    .and_then(|v| v.get("error")?.as_str().map(str::to_owned))
                    .unwrap_or_else(|| format!("HTTP {code}"));
                Err(reason)
            }
            Err(e) => Err(e.to_string())
        };
        let _ = tx.send(result);
    });
    rx
}

pub fn download_bundle(base_url: String, session: Session) -> Receiver<Result<Vec<u8>, String>> {
    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        let url = format!("{}/api/rooms/{}/bundle", base_url.trim().trim_end_matches('/'), session.code);
        let response = ureq::AgentBuilder::new().timeout(Duration::from_secs(25)).build()
            .get(&url)
            .set("authorization", &format!("Bearer {}", session.token))
            .call();
        let result = match response {
            Ok(r) => {
                let mut bytes = Vec::new();
                r.into_reader().take(2_000_001).read_to_end(&mut bytes)
                    .map_err(|e| e.to_string()).and_then(|_| {
                        if bytes.len() > 2_000_000 {
                            Err("Слишком большой ZIP-пак".to_owned())
                        } else {
                            Ok(bytes)
                        }
                    })
            }
            Err(ureq::Error::Status(code, _)) => Err(format!("Архив недоступен: HTTP {code}")),
            Err(e) => Err(e.to_string())
        };
        let _ = tx.send(result);
    });
    rx
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::net::TcpListener;
    use std::time::Instant;

    #[test]
    fn https_room_connection_starts_a_tls_handshake() {
        let listener = TcpListener::bind(("127.0.0.1", 0)).unwrap();
        listener.set_nonblocking(true).unwrap();
        let session = Session {
            code: "TESTROOM".into(),
            player_id: "test-player".into(),
            token: "test-token".into(),
        };
        let (_sender, receiver) =
            connect(&format!("https://{}", listener.local_addr().unwrap()), &session).unwrap();
        let deadline = Instant::now() + Duration::from_secs(5);
        loop {
            match listener.accept() {
                Ok((mut stream, _)) => {
                    stream.set_read_timeout(Some(Duration::from_secs(3))).unwrap();
                    let mut header = [0; 5];
                    stream.read_exact(&mut header).expect("TLS record header");
                    assert_eq!(header[0], 0x16, "the client must start with a TLS handshake");
                    return;
                }
                Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                    if let Some(ewebsock::WsEvent::Error(error)) = receiver.try_recv() {
                        panic!("WebSocket failed before the handshake: {error}");
                    }
                    assert!(Instant::now() < deadline, "WebSocket never connected");
                    thread::sleep(Duration::from_millis(10));
                }
                Err(error) => panic!("could not accept local TLS connection: {error}"),
            }
        }
    }
}
